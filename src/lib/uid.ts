/**
 * A random UUID (v4) for new elements and groups. `crypto.randomUUID` exists only in secure
 * contexts (https, or localhost), so a phone opening the dev server at http://192.168.x.x has
 * none; `crypto.getRandomValues` works everywhere, browser and Node.
 */
export function uid(): string {
  if (typeof crypto.randomUUID === 'function') return crypto.randomUUID();
  const b = crypto.getRandomValues(new Uint8Array(16));
  b[6] = (b[6] & 0x0f) | 0x40; // version 4
  b[8] = (b[8] & 0x3f) | 0x80; // variant 10xx
  const h = [...b].map((x) => x.toString(16).padStart(2, '0')).join('');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}
