export const professionOf = (topic: string | null) => PROFESSIONS.find((p) => p.topic === topic) ?? null;

const PLACEHOLDERS: Record<string, BrandDetail> = {
  'שם העסק': 'businessName',
  'טלפון': 'phone',
  'סלוגן': 'slogan',
  'כתובת': 'address',
  'אתר': 'website',
};

/**
 * A message with the kit written in. A line that relied on a detail the kit doesn't have is dropped whole when
 * nothing else is left on it, and the placeholder alone is dropped otherwise: no brackets reach a customer.
 */
export function fillMessage(body: string, kit: Pick<BrandKit, BrandDetail>): string {
  return body
    .split('\n')
    .flatMap((line) => {
      const filled = line.replace(/\{([^}]+)\}/g, (_m, name: string) => kit[PLACEHOLDERS[name]]?.trim() ?? '');
      // a line that had a placeholder and ends on nothing but punctuation has nothing left to say
      const empty = /\{[^}]+\}/.test(line) && !filled.replace(/[\s:,.\-!]/g, '');
      return empty ? [] : [filled.replace(/:\s*$/, '').trimEnd()];
    })
    .join('\n');
}
